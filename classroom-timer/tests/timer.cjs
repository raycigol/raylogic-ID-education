const assert=require('node:assert/strict'),path=require('node:path');
const {Timer,format}=require(process.argv[2]||path.join(__dirname,'../timer-core.js'));
let t=new Timer(600);t.start(1000);
assert.equal(t.remaining(61000),540);
assert.equal(t.remaining(181234),419.766,'elapsed time uses deadline, not interval tick count');
t.pause(181234);assert.equal(t.phase,'paused');assert.equal(t.remaining(900000),419.766);
t.start(900000);assert.equal(t.remaining(901000),418.766);
const restored=Timer.restore(t.snapshot(),902000);assert.equal(restored.remaining(902000),417.766);
assert.equal(restored.tick(2000000),true);assert.equal(restored.phase,'finished');assert.equal(restored.remaining(3000000),0);assert.equal(restored.tick(3000000),false,'finish occurs once');
assert.equal(Timer.restore(t.snapshot(),3000000).phase,'finished','expired restored timers stop at zero');
t=new Timer(60);t.start(0);t.shift(60,10000);assert.equal(t.remaining(10000),110);
t.shift(-300,10000);assert.equal(t.phase,'finished');assert.equal(t.remaining(10000),0);
t.shift(60,10000);assert.equal(t.phase,'paused');assert.equal(t.remaining(10000),60);
t.reset();assert.equal(t.phase,'ready');assert.equal(t.remaining(10000),60);
assert.throws(()=>t.setDuration(0));assert.throws(()=>t.setDuration(1.1));
assert.equal(Timer.restore({duration:600,left:600,phase:'running',deadline:Infinity},0),null);
assert.equal(Timer.restore({duration:600,left:-1,phase:'paused'},0),null);
const clean=Timer.restore({duration:600,left:600,phase:'ready',remaining:'bad'},0);assert.equal(clean.remaining(0),600);
assert.equal(format(59.1),'01:00');assert.equal(format(0),'00:00');assert.equal(format(-10),'00:00');assert.equal(format(600),'10:00');
console.log('PASS: deadline-based timing; pause/resume; reload recovery; finish once at zero; adjust/reset; stored-state validation and formatting');
